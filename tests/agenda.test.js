// Run: deno run --allow-read tests/agenda.test.js
import assert from "node:assert/strict";
import { runInNewContext } from "node:vm";
import { parseHTML } from "npm:linkedom@0.18.12";

const coreCode = await Deno.readTextFile(new URL("../assets/js/agenda-core.js", import.meta.url));
const appCode = await Deno.readTextFile(new URL("../assets/js/agenda.js", import.meta.url));
const catalog = JSON.parse(await Deno.readTextFile(new URL("../data/agenda.json", import.meta.url)));
const context = { URL, URLSearchParams, TextEncoder, TextDecoder, btoa, atob };
runInNewContext(coreCode, context);
const core = context.SparkAgenda;
const seed = core.normalize(catalog.events[0]);
assert.equal(core.arrival(seed).time, "18:30");
assert.equal(core.arrival({ ...seed, time: "00:15" }).date, "2026-11-21");
assert.equal(core.arrival({ ...seed, time: "00:15" }).time, "23:45");
assert.throws(() => core.normalize({ ...seed, date: "2026-02-30" }));
assert.throws(() => core.normalize({ ...seed, time: "25:01" }));
assert.throws(() => core.normalize({ ...seed, gallery: "javascript:alert(1)" }));
assert.throws(() => core.normalize({ ...seed, instagram: "https://instagram.com.evil.example/" }));
assert.throws(() => core.normalize({ ...seed, arrivalMinutes: 10 }));
assert.throws(() => core.decode("broken"));
assert.throws(() => core.decode("a".repeat(30001)));
const edited = { ...seed, title: 'Formatura <img src=x onerror="alert(1)"> 🎓', photography: "Édi e Delliz", notes: "Atenção!\nAguardar liberação." };
const shared = core.eventUrl(edited, "https://sparkfilmes.com.br/agenda/", true);
const decoded = core.decode(new URL(shared).hash.slice(8));
assert.equal(decoded.title, edited.title);
assert.equal(decoded.notes, edited.notes);
assert.equal(core.merge([seed], [edited]).length, 1);
assert.equal(core.merge([seed], [edited])[0].photography, edited.photography);
assert.equal(core.maps(seed).google, seed.googleMaps);
assert.equal(new URL(core.maps({ ...seed, googleMaps: "" }).google).searchParams.get("query"), seed.address);
assert.throws(() => core.normalize({ ...seed, googleMaps: "https://evil.example/" }));
assert.throws(() => core.normalize({ ...seed, photos: [{ src: 'javascript:alert(1)' }] }));
assert.equal(decoded.photos.length, seed.photos.length, "Shared links preserve venue photos");
assert.equal(new URL(core.maps(seed).waze).searchParams.get("q"), seed.address);

async function runPage(file, href, storage = "[]", failFetch = false) {
  const html = await Deno.readTextFile(new URL("../agenda/" + file, import.meta.url));
  const { document, Event } = parseHTML(html);
  let clipboard = "", fetches = 0;
  const location = new URL(href);
  location.reload = () => {};
  document.querySelectorAll("dialog").forEach(dialog => { dialog.showModal = () => { dialog.open = true; }; dialog.close = () => { dialog.open = false; }; });
  const sandbox = { ...context, document, window: { print() {} }, location, navigator: { clipboard: { writeText: async value => { clipboard = value; } } }, localStorage: { getItem: () => storage }, crypto, setTimeout: () => 0, clearTimeout() {}, fetch: async () => { fetches++; return { ok: !failFetch, json: async () => catalog }; } };
  await runInNewContext(appCode, sandbox);
  return { document, Event, clipboard: () => clipboard, fetches: () => fetches };
}
const publicPage = await runPage("evento.html", "https://sparkfilmes.com.br/agenda/evento.html?id=" + seed.id);
assert(publicPage.document.body.textContent.includes("18:30"), publicPage.document.body.textContent);
assert(publicPage.document.body.textContent.includes("Delliz e Edi"));
assert(publicPage.document.body.textContent.includes("Felipe e Bruno"));
assert(publicPage.document.body.textContent.includes("não irá até as 22h"));
assert.equal(publicPage.document.querySelectorAll(".venue-photo-grid img").length, 3);
assert.equal(publicPage.document.querySelector(".venue-instagram").getAttribute("href"), "https://www.instagram.com/bretaskids2/");
assert(!publicPage.document.body.textContent.includes("Sobre o evento"));
assert(!publicPage.document.body.textContent.includes("Aarão"));
publicPage.document.querySelector("#share-event").click();
assert.equal(new URL(publicPage.clipboard()).searchParams.get("id"), seed.id);
const sharedPage = await runPage("evento.html", shared, "[]", true);
assert.equal(sharedPage.fetches(), 0, "Shared snapshot works independently of local storage and the catalog");
assert.equal(sharedPage.document.querySelector("h1").textContent, edited.title + ".");
assert.equal(sharedPage.document.querySelectorAll("[onerror]").length, 0, "Shared text must not inject HTML");
const missing = await runPage("evento.html", "https://sparkfilmes.com.br/agenda/evento.html?id=missing");
assert(missing.document.body.textContent.includes("Evento não encontrado"));
const agenda = await runPage("index.html", "https://sparkfilmes.com.br/agenda/");
assert.equal(agenda.document.querySelectorAll(".calendar-day").length, 30);
assert.equal(agenda.document.querySelectorAll(".has-event").length, 1);
agenda.document.querySelector("#next-month").click();
assert.equal(agenda.document.querySelectorAll(".calendar-day").length, 31);
assert(agenda.document.querySelector("#day-events").textContent.includes("Dia livre"));
agenda.document.querySelector("#prev-month").click();
agenda.document.querySelector('[data-date="2026-11-22"]').dispatchEvent(new agenda.Event("click", { bubbles: true }));
assert(agenda.document.querySelector("#day-events").textContent.includes("Formatura IEMAB"));
const restored = await runPage("index.html", "https://sparkfilmes.com.br/agenda/", JSON.stringify([edited]));
assert.equal(restored.document.querySelector(".agenda-event-card h3").textContent, edited.title);
assert(new URL(restored.document.querySelector(".agenda-event-card a").href).hash.startsWith("#evento="));
const failed = await runPage("index.html", "https://sparkfilmes.com.br/agenda/", "[]", true);
assert(failed.document.querySelector("#load-status").textContent.includes("Não foi possível"));
console.log("Agenda: horários, validação, calendário, restauração, compartilhamento sem armazenamento e proteção de conteúdo verificados.");
